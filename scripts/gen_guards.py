out = []
w = out.append
w("-- GENERATED by scripts/gen_guards.py -- the triggers below ARE the owner-state protections.")
w("-- They rely on the application-defined function current_actor(), which each connection")
w("-- registers for its role. A connection without it (e.g. the sqlite3 shell) cannot write")
w("-- any guarded table: SQLite raises 'no such function' and the write fails closed.")
w("")
w("-- Seed the lifecycle table, then freeze it.")
for f, t, a, d in T:
    dec = "NULL" if d is None else f"'{d}'"
    w(f"INSERT INTO state_transition VALUES ('{f}','{t}',',{a},',{dec});")
